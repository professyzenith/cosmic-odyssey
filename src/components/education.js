export function buildEducation() {
  Object.entries(EDU_DATA).forEach(([level, cards]) => {
    const grid = document.getElementById(`edu-grid-${level}`);
    if (!grid) return;

    grid.innerHTML = cards.map((card, i) => `
      <div class="edu-card reveal" style="transition-delay:${i * 60}ms">
        <div class="edu-card-icon" style="--edu-color:${card.color}" aria-hidden="true">${card.icon}</div>
        <h3 class="edu-card-title">${card.title}</h3>
        <p class="edu-card-text">${card.text}</p>
        <div class="edu-card-bar" style="background:${card.color}33">
          <div class="edu-card-bar-fill" style="background:${card.color}"></div>
        </div>
      </div>
    `).join('');
  });

  // Force-reveal beginner cards (default active tab) immediately
  // — IntersectionObserver can't fire on display:none containers
  // so we manually trigger visible state for the active tab
  requestAnimationFrame(() => {
    const beginnerGrid = document.getElementById('edu-grid-beginner');
    if (beginnerGrid) {
      beginnerGrid.querySelectorAll('.edu-card').forEach((el, i) => {
        setTimeout(() => {
          el.classList.add('visible');
          const fill = el.querySelector('.edu-card-bar-fill');
          if (fill) fill.style.width = '100%';
        }, 200 + i * 80);
      });
    }
  });

  // Tab switching
  document.querySelectorAll('.edu-tab').forEach(tab => {
    tab.addEventListener('click', () => {
      const level = tab.dataset.level;

      document.querySelectorAll('.edu-tab').forEach(t => t.classList.remove('active'));
      document.querySelectorAll('.edu-level').forEach(l => l.classList.remove('active'));

      tab.classList.add('active');
      const levelEl = document.getElementById(`edu-cards-${level}`);
      if (levelEl) {
        levelEl.classList.add('active');
        // Cards in non-active tabs were display:none when observer ran, so force visible
        requestAnimationFrame(() => {
          levelEl.querySelectorAll('.edu-card').forEach((el, i) => {
            setTimeout(() => el.classList.add('visible'), i * 60);
          });
        });
      }
    });
  });
}
